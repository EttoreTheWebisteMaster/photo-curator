"""SQLite store. Holds metadata only: photos are never copied or modified."""
from __future__ import annotations

import sqlite3
from pathlib import Path

SCHEMA = """
CREATE TABLE IF NOT EXISTS photos (
    id            INTEGER PRIMARY KEY,
    path          TEXT NOT NULL UNIQUE,
    size          INTEGER NOT NULL,
    mtime         REAL NOT NULL,
    sha256        TEXT,
    width         INTEGER,
    height        INTEGER,
    taken_at      TEXT,
    taken_source  TEXT,
    time_known    INTEGER,
    phash         TEXT,
    sharpness     REAL,
    brightness    REAL,
    shadow_clip   REAL,
    highlight_clip REAL,
    is_utility    INTEGER DEFAULT 0,
    duplicate_of  INTEGER REFERENCES photos(id),  -- id of the kept original (NULL = not a copy)
    rejected_reviewed_at TEXT,      
    error         TEXT,
    scanned_at    TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_photos_taken_at ON photos(taken_at);
CREATE INDEX IF NOT EXISTS idx_photos_sha256 ON photos(sha256);

CREATE TABLE IF NOT EXISTS groups (
    photo_id  INTEGER PRIMARY KEY REFERENCES photos(id) ON DELETE CASCADE,
    group_id  INTEGER NOT NULL,
    run_id    TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_groups_group ON groups(group_id);

-- Step 2: visual embeddings, one row per (photo, model).
-- float32 little-endian, L2-normalized -> cosine = dot product.
CREATE TABLE IF NOT EXISTS embeddings (
    photo_id    INTEGER NOT NULL REFERENCES photos(id) ON DELETE CASCADE,
    model       TEXT NOT NULL,
    dim         INTEGER NOT NULL,
    vector      BLOB NOT NULL,
    created_at  TEXT NOT NULL,
    PRIMARY KEY (photo_id, model)
);
CREATE INDEX IF NOT EXISTS idx_embeddings_model ON embeddings(model);

-- Step 2: user labels for the benchmark and (later) the personal ranker.
-- "winner" = best in its group, "forse" = keep but not sure, "rejected" = discard.
CREATE TABLE IF NOT EXISTS labels (
    id          INTEGER PRIMARY KEY,
    group_id    INTEGER NOT NULL,
    photo_id    INTEGER NOT NULL REFERENCES photos(id) ON DELETE CASCADE,
    label       TEXT NOT NULL,
    reason      TEXT,
    created_at  TEXT NOT NULL,
    UNIQUE(group_id, photo_id, label)
);
CREATE INDEX IF NOT EXISTS idx_labels_group ON labels(group_id);
CREATE INDEX IF NOT EXISTS idx_labels_photo ON labels(photo_id);

-- Step 2: benchmark results, one row per (run, method).
CREATE TABLE IF NOT EXISTS benchmark_runs (
    id          INTEGER PRIMARY KEY,
    run_id      TEXT NOT NULL,
    task        TEXT NOT NULL,           -- 'scorer' (later: 'grouping')
    method      TEXT NOT NULL,
    groups      INTEGER NOT NULL,        -- groups evaluated
    hits        INTEGER NOT NULL,
    accuracy    REAL NOT NULL,
    created_at  TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_bench_run ON benchmark_runs(run_id);

CREATE TABLE IF NOT EXISTS settings (
    key   TEXT PRIMARY KEY,
    value TEXT
);

CREATE TABLE IF NOT EXISTS manifest (
    id              INTEGER PRIMARY KEY,
    commit_id       TEXT NOT NULL,
    photo_id        INTEGER REFERENCES photos(id),
    companion_of    INTEGER,
    original_path   TEXT NOT NULL,
    new_path        TEXT NOT NULL,
    sha256_before   TEXT,
    sha256_after    TEXT,
    role            TEXT NOT NULL,
    source          TEXT NOT NULL DEFAULT 'review',
    size            INTEGER,
    moved_at        TEXT NOT NULL,
    undone_at       TEXT
);
CREATE INDEX IF NOT EXISTS idx_manifest_commit ON manifest(commit_id);
CREATE INDEX IF NOT EXISTS idx_manifest_photo ON manifest(photo_id);

-- Reject examples: centroids of photos the user has rejected, used to flag
-- similar photos in future analyses.
CREATE TABLE IF NOT EXISTS reject_examples (
    id          INTEGER PRIMARY KEY,
    commit_id   TEXT,
    source      TEXT NOT NULL,   -- "group" | "suggested"
    model       TEXT NOT NULL,
    dim         INTEGER NOT NULL,
    vector      BLOB NOT NULL,
    n_photos    INTEGER NOT NULL,
    created_at  TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_reject_examples_model ON reject_examples(model);

-- Per-photo suggestions from the reject-learning system.
-- If the user dismisses a suggestion, dismissed_at is set (photo goes back into groups).
CREATE TABLE IF NOT EXISTS photo_suggestions (
    photo_id     INTEGER PRIMARY KEY REFERENCES photos(id) ON DELETE CASCADE,
    example_id   INTEGER REFERENCES reject_examples(id),
    similarity   REAL NOT NULL,
    computed_at  TEXT NOT NULL,
    dismissed_at TEXT
);

-- Step 3: workflow state per group. One row per group_id from `groups` table.
-- Regenerated by `group.build_groups` (status resets to 'pending', winner = first photo).
CREATE TABLE IF NOT EXISTS group_states (
    group_id                INTEGER PRIMARY KEY,
    group_key               TEXT,
    status                  TEXT NOT NULL DEFAULT 'pending',  -- pending | completed | deleted
    current_winner_photo_id INTEGER REFERENCES photos(id),
    decided_at              TEXT,
    updated_at              TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_group_states_status ON group_states(status);

-- A confirmed group choice and the exact photo set it compared. The stable
-- group key is derived from sorted photo IDs, not the ephemeral group_id.
CREATE TABLE IF NOT EXISTS group_feedback (
    group_key       TEXT PRIMARY KEY,
    photo_ids       TEXT NOT NULL,
    winner_photo_id INTEGER NOT NULL REFERENCES photos(id),
    ai_assisted     INTEGER NOT NULL DEFAULT 0,
    active          INTEGER NOT NULL DEFAULT 1,
    created_at      TEXT NOT NULL
);

-- Only explicit individual keep/reject actions train the discard model.
CREATE TABLE IF NOT EXISTS user_feedback (
    id                   INTEGER PRIMARY KEY,
    photo_id             INTEGER NOT NULL REFERENCES photos(id) ON DELETE CASCADE,
    source               TEXT NOT NULL,
    label                TEXT NOT NULL CHECK(label IN ('keep', 'reject')),
    active               INTEGER NOT NULL DEFAULT 1,
    previous_is_utility  INTEGER,
    previous_duplicate_of INTEGER,
    previous_reviewed_at TEXT,
    previous_user_reject INTEGER,
    previous_suggested_reject INTEGER,
    previous_dismissed_at TEXT,
    created_at           TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_user_feedback_active ON user_feedback(active, label);
"""


def _migrate(conn: sqlite3.Connection) -> None:
    cols = {r["name"] for r in conn.execute("PRAGMA table_info(photos)")}
    added = False
    if "time_known" not in cols:
        conn.execute("ALTER TABLE photos ADD COLUMN time_known INTEGER")
        added = True
    if "is_utility" not in cols:
        conn.execute("ALTER TABLE photos ADD COLUMN is_utility INTEGER DEFAULT 0")
        added = True
    if "duplicate_of" not in cols:
        conn.execute("ALTER TABLE photos ADD COLUMN duplicate_of INTEGER")
        added = True
    if "rejected_reviewed_at" not in cols:
        conn.execute("ALTER TABLE photos ADD COLUMN rejected_reviewed_at TEXT")
        added = True
    if "committed_at" not in cols:
        conn.execute("ALTER TABLE photos ADD COLUMN committed_at TEXT")
        added = True
    manifest_cols = {r["name"] for r in conn.execute("PRAGMA table_info(manifest)")}
    if manifest_cols and "size" not in manifest_cols:
        conn.execute("ALTER TABLE manifest ADD COLUMN size INTEGER")
        added = True
    if manifest_cols and "source" not in manifest_cols:
        conn.execute("ALTER TABLE manifest ADD COLUMN source TEXT NOT NULL DEFAULT 'review'")
        added = True
    if "suggested_reject" not in cols:
        conn.execute("ALTER TABLE photos ADD COLUMN suggested_reject INTEGER DEFAULT 0")
        added = True
    if "user_reject" not in cols:
        conn.execute("ALTER TABLE photos ADD COLUMN user_reject INTEGER DEFAULT 0")
        added = True
    if "brightness" not in cols:
        conn.execute("ALTER TABLE photos ADD COLUMN brightness REAL")
        added = True
    if "shadow_clip" not in cols:
        conn.execute("ALTER TABLE photos ADD COLUMN shadow_clip REAL")
        added = True
    if "highlight_clip" not in cols:
        conn.execute("ALTER TABLE photos ADD COLUMN highlight_clip REAL")
        added = True
    state_cols = {r["name"] for r in conn.execute("PRAGMA table_info(group_states)")}
    if state_cols and "group_key" not in state_cols:
        conn.execute("ALTER TABLE group_states ADD COLUMN group_key TEXT")
        added = True
    feedback_cols = {r["name"] for r in conn.execute("PRAGMA table_info(group_feedback)")}
    if feedback_cols and "ai_assisted" not in feedback_cols:
        conn.execute("ALTER TABLE group_feedback ADD COLUMN ai_assisted INTEGER NOT NULL DEFAULT 0")
        added = True
    if added:
        conn.commit()


def connect(db_path: str | Path) -> sqlite3.Connection:
    conn = sqlite3.connect(str(db_path))
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    conn.executescript(SCHEMA)
    _migrate(conn)
    return conn